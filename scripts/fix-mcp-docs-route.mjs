import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const out = path.join(root, 'dist');

const routePairs = [
  { source: '/mcp.html', target: '/mcp-docs/' },
  { source: '/pt-br/mcp.html', target: '/pt-br/mcp-docs/' }
];

function fileFor(url) {
  const rel = String(url).replace(/^\//, '');
  if (url.endsWith('/')) return path.join(out, rel, 'index.html');
  return path.join(out, rel);
}

function replaceRouteRefs(value) {
  return String(value)
    .replaceAll('/pt-br/mcp.html', '/pt-br/mcp-docs/')
    .replaceAll('/mcp.html', '/mcp-docs/');
}

for (const {source, target} of routePairs) {
  const sourceFile = fileFor(source);
  if (!fs.existsSync(sourceFile)) throw new Error(`Missing generated MCP documentation: ${sourceFile}`);
  const targetFile = fileFor(target);
  fs.mkdirSync(path.dirname(targetFile), {recursive: true});
  fs.writeFileSync(targetFile, replaceRouteRefs(fs.readFileSync(sourceFile, 'utf8')));
  fs.unlinkSync(sourceFile);
}

const walk = dir => fs.readdirSync(dir, {withFileTypes: true}).flatMap(entry => {
  const p = path.join(dir, entry.name);
  return entry.isDirectory() ? walk(p) : [p];
});

// Footer links are generated by the shared layout before the MCP docs route is
// relocated. Normalize every generated HTML file so the human-facing link never
// collides with the protocol endpoint at /mcp.
for (const file of walk(out).filter(file => file.endsWith('.html'))) {
  const html = fs.readFileSync(file, 'utf8');
  const next = replaceRouteRefs(html);
  if (next !== html) fs.writeFileSync(file, next);
}

const searchFile = path.join(out, 'data', 'search-index.json');
if (fs.existsSync(searchFile)) {
  const index = JSON.parse(fs.readFileSync(searchFile, 'utf8'));
  for (const items of Object.values(index.locales || {})) {
    if (!Array.isArray(items)) continue;
    for (const item of items) {
      if (item?.id === 'page:mcp' && item.url) item.url = replaceRouteRefs(item.url);
    }
  }
  fs.writeFileSync(searchFile, `${JSON.stringify(index)}\n`);
}

const sitemapFile = path.join(out, 'sitemap.xml');
if (fs.existsSync(sitemapFile)) {
  const xml = fs.readFileSync(sitemapFile, 'utf8');
  fs.writeFileSync(sitemapFile, replaceRouteRefs(xml));
}

// Build invariant: the documentation route must never normalize into /mcp.
const stale = walk(out).filter(file => {
  if (!/\.(html|xml|json)$/.test(file)) return false;
  return fs.readFileSync(file, 'utf8').includes('/mcp.html');
});
if (stale.length) throw new Error(`Stale /mcp.html references remain: ${stale.join(', ')}`);

for (const {target} of routePairs) {
  if (!fs.existsSync(fileFor(target))) throw new Error(`Missing relocated MCP documentation: ${target}`);
}

console.log('MCP documentation routes ready: /mcp-docs/ and /pt-br/mcp-docs/.');
